    std::uint8_t glyphRow(char character, std::uint32_t row) noexcept
    {
        if (row >= kGlyphHeight)
        {
            return 0;
        }

        const auto code = static_cast<unsigned char>(character);
        if (code < static_cast<unsigned char>(kFirstGlyph)
            || code > static_cast<unsigned char>(kLastGlyph))
        {
            return 0;
        }

        const auto index =
            static_cast<std::size_t>(code)
            - static_cast<std::size_t>(kFirstGlyph);
        return kGlyphs.at(index).at(row);
    }

